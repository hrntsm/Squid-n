//! Newton 反復の共通足場（反復上限・相対許容誤差・収束判定）。
//!
//! ソルバ内の Newton 反復は解析経路ごとにループ本体が大きく異なる
//! （弧長法の円筒拘束、変位制御の二重求解と λ 決定、動的解析の慣性・減衰項、
//! 組立てキャッシュ・作業バッファの使い回し）ため、ループ骨格は共通化せず、
//! 収束規約（反復上限・相対許容誤差・相対残差判定）だけを本モジュールへ集約する。
//!
//! 収束判定の基準ノルム（分母）は解析種別ごとに物理的意味が異なる
//! （弧長法は λ 依存の外力ノルム、動的解析は長期荷重を除く動的外力ノルム、
//! 静的漸増は目標外力ノルム）ため、その定義は各呼び出し側の責務とし、
//! 本型は「残差ノルム < tol × 基準ノルム」の形だけを共通に提供する。

/// Newton 反復の収束規約（反復上限と相対許容誤差）。
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct NewtonCriteria {
    /// 反復の最大回数。
    pub max_iter: usize,
    /// 相対許容誤差。残差ノルムが `tol ×` 基準ノルムを下回れば収束とする。
    pub tol: f64,
}

impl NewtonCriteria {
    /// 反復上限と相対許容誤差を指定して作る。
    pub const fn new(max_iter: usize, tol: f64) -> Self {
        Self { max_iter, tol }
    }

    /// 相対残差判定。`r_norm < tol × ref_norm` で収束。
    /// 基準ノルム `ref_norm`（外力ノルム等）の定義は呼び出し側の責務。
    pub fn converged(&self, r_norm: f64, ref_norm: f64) -> bool {
        r_norm < self.tol * ref_norm
    }

    /// 反復レンジ `0..max_iter`（`for _iter in criteria.iters()` の形で使う）。
    pub fn iters(&self) -> std::ops::Range<usize> {
        0..self.max_iter
    }
}

/// 静的漸増解析（プッシュオーバーの荷重制御・変位制御、長期載荷）の共通規約。
///
/// 弾性域は 1〜2 回で収束し、上限 50 回は塑性進行時の余裕
/// （ステップ内で接線を組み直す準ニュートン形式のため多めに取る）。
/// 基準ノルムは外力ノルムと 1.0 の大きい方（`f_norm.max(1.0)`）。
pub const STATIC_NEWTON: NewtonCriteria = NewtonCriteria::new(50, 1e-6);

/// L2 ノルム（Newton 反復の残差・基準ノルム算定の共通形）。
pub fn l2_norm(v: &[f64]) -> f64 {
    v.iter().map(|x| x * x).sum::<f64>().sqrt()
}

/// 減衰しきった応答で基準ノルムを止める下限の比率。
///
/// 解析中に観測した力のスケールの最大値に対し、この比率を下回った時刻では基準を
/// それ以上下げない。応答が最大の 1% を切った領域は工学的に無視できる大きさであり、
/// そこで判定を続けても意味がないためである。
///
/// この下限がないと、応答が減衰しきった時刻で 3 項すべてが 1 N を下回り、基準が床の
/// 1.0 まで落ちて判定が絶対値判定に化ける（[`dynamic_reference_norm`] の解説参照）。
/// そのとき履歴則は微小振幅でチャタリングしており、残差は力のスケールに対して
/// 相対 10% 程度で振動する。実測では最大 6.1e7 N の解析の末尾で、力が 6e-4 N まで
/// 落ちたところで残差が 1e-4 N から下がらなくなった。比率 1% はこれを収束と
/// 認めるのに必要な余裕から定めている。
const DECAYED_SCALE_FLOOR_RATIO: f64 = 1.0e-2;

/// この時刻の力のスケール。動的釣り合い `p = f_int + C·v + M·a` の**動的な 3 項の
/// ノルムの最大**を返す（長期荷重 f0 は含めない）。
pub fn dynamic_force_scale(p: &[f64], m_a: &[f64], c_v: &[f64]) -> f64 {
    let norm = |v: &[f64]| v.iter().map(|x| x * x).sum::<f64>().sqrt();
    norm(p).max(norm(m_a)).max(norm(c_v))
}

/// 動的解析（時刻歴）の収束判定に用いる基準ノルム。
///
/// `scale` はこの時刻の力のスケール（[`dynamic_force_scale`]）、`peak_scale` は解析中に
/// 観測したその最大値。長期荷重 f0 は含めない（含めると長期が卓越するモデルで判定が
/// 過度に緩む）。
///
/// # なぜ瞬間の外力だけでは足りないか
///
/// 動的外力 `p` だけを基準にすると、**地動加速度がゼロを横切る時刻**で基準が消えて
/// 床の 1.0（N）まで落ち、判定が「残差 < tol × 1 N」という絶対値判定に化ける。
/// 実建物では内力・慣性力が 1e7 N 規模あり、悪条件な有効剛性の線形解が持つ残差
/// （概ね `条件数 × ε × 力のスケール`）が 1e-1 N 規模になるため、**原理的に到達
/// できない閾値**になってしまう。正弦波なら毎周期 2 回、実波形でも頻繁に通る時刻
/// なので避けようがない。地動が 0 でも構造は動いており慣性力・減衰力は大きいので、
/// 3 項の最大を採れば基準は消えない。
///
/// # なぜ最大値に対する下限が要るか
///
/// 3 項の最大だけでは、**応答が減衰しきった時刻**で同じ破綻が戻る。長い波形の末尾では
/// 3 項すべてが 1 N を下回り、また床の 1.0 まで落ちるためである。そこで解析中に観測した
/// 力のスケールの最大値に対する下限（[`DECAYED_SCALE_FLOOR_RATIO`]）を設け、
/// 工学的に無視できる大きさまで減衰した領域では基準をそれ以上下げない。
///
/// 最低値 1.0 は、解析を通して一度も動いていない（`peak_scale` も 0）ときに
/// 0 除算を避けるための床である。
pub fn dynamic_reference_norm(scale: f64, peak_scale: f64) -> f64 {
    scale.max(peak_scale * DECAYED_SCALE_FLOOR_RATIO).max(1.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 外力が 0 でも、慣性力・減衰力があれば力のスケールはそちらを採る。
    /// 地動加速度がゼロを横切る時刻に相当する。
    #[test]
    fn 外力がゼロでも慣性力を力のスケールに採る() {
        let scale = dynamic_force_scale(&[0.0, 0.0, 0.0], &[3.0, 4.0, 0.0], &[1.0, 0.0, 0.0]);
        assert_eq!(scale, 5.0);
    }

    /// 3 項のうち最大のものを採る。
    #[test]
    fn 動的釣り合いの各項の最大を採る() {
        assert_eq!(dynamic_force_scale(&[7.0], &[3.0], &[5.0]), 7.0);
        assert_eq!(dynamic_force_scale(&[3.0], &[7.0], &[5.0]), 7.0);
        assert_eq!(dynamic_force_scale(&[3.0], &[5.0], &[7.0]), 7.0);
    }

    /// 応答が減衰しきっても、基準は解析中の最大値の 1% までしか下がらない。
    ///
    /// これがないと、長い波形の末尾で基準が床の 1.0 まで落ち、判定が到達不能な
    /// 絶対値判定に化ける。
    #[test]
    fn 減衰しきった時刻は最大値に対する下限で止まる() {
        let peak = 6.0e7;
        // 力が 6e-4 N まで落ちた時刻。基準は 6e5（最大の 1%）で止まる。
        assert_eq!(dynamic_reference_norm(6.0e-4, peak), 6.0e5);
        // 応答が大きい時刻は瞬間値がそのまま基準になる（下限は効かない）。
        assert_eq!(dynamic_reference_norm(1.5e7, peak), 1.5e7);
    }

    /// 解析を通して一度も動いていないときは床の 1.0 を返す（0 除算の回避）。
    #[test]
    fn 一度も動いていなければ床の一を返す() {
        assert_eq!(dynamic_reference_norm(0.0, 0.0), 1.0);
        assert_eq!(dynamic_reference_norm(0.5, 20.0), 1.0);
    }
}
