//! Newton 反復の共通足場（反復上限・相対許容誤差・収束判定）。
//!
//! ソルバ内の Newton 反復は解析経路ごとにループ本体が大きく異なる
//! （弧長法の円筒拘束、変位制御の二重求解と λ 決定、動的解析の慣性・減衰項、
//! 組立てキャッシュ・作業バッファの使い回し）ため、ループ骨格は共通化せず、
//! 収束規約（反復上限・相対許容誤差・相対残差判定）だけを本モジュールへ集約する。
//!
//! 収束判定の基準ノルム（分母）は解析種別ごとに物理的意味が異なる
//! （弧長法は λ 依存の外力ノルム、動的解析は長期荷重を除く動的外力ノルム、
//! 静的漸増は目標外力ノルム）ため、その定義は各呼び出し側の責務とし、
//! 本型は「残差ノルム < tol × 基準ノルム」の形だけを共通に提供する。

/// Newton 反復の収束規約（反復上限と相対許容誤差）。
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct NewtonCriteria {
    /// 反復の最大回数。
    pub max_iter: usize,
    /// 相対許容誤差。残差ノルムが `tol ×` 基準ノルムを下回れば収束とする。
    pub tol: f64,
}

impl NewtonCriteria {
    /// 反復上限と相対許容誤差を指定して作る。
    pub const fn new(max_iter: usize, tol: f64) -> Self {
        Self { max_iter, tol }
    }

    /// 相対残差判定。`r_norm < tol × ref_norm` で収束。
    /// 基準ノルム `ref_norm`（外力ノルム等）の定義は呼び出し側の責務。
    pub fn converged(&self, r_norm: f64, ref_norm: f64) -> bool {
        r_norm < self.tol * ref_norm
    }

    /// 反復レンジ `0..max_iter`（`for _iter in criteria.iters()` の形で使う）。
    pub fn iters(&self) -> std::ops::Range<usize> {
        0..self.max_iter
    }
}

/// 静的漸増解析（プッシュオーバーの荷重制御・変位制御、長期載荷）の共通規約。
///
/// 弾性域は 1〜2 回で収束し、上限 50 回は塑性進行時の余裕
/// （ステップ内で接線を組み直す準ニュートン形式のため多めに取る）。
/// 基準ノルムは外力ノルムと 1.0 の大きい方（`f_norm.max(1.0)`）。
pub const STATIC_NEWTON: NewtonCriteria = NewtonCriteria::new(50, 1e-6);

/// L2 ノルム（Newton 反復の残差・基準ノルム算定の共通形）。
pub fn l2_norm(v: &[f64]) -> f64 {
    v.iter().map(|x| x * x).sum::<f64>().sqrt()
}

/// 動的解析（時刻歴）の収束判定に用いる基準ノルム。
///
/// 動的釣り合い `p = f_int + C·v + M·a` の**動的な 3 項のノルムの最大**を採る
/// （長期荷重 f0 は含めない。含めると長期が卓越するモデルで判定が過度に緩む）。
/// 最低値 1.0 は、応答が完全に静止していて 3 項すべてが 0 のときに 0 除算を
/// 避けるための床である。
///
/// # なぜ外力だけでは足りないか
///
/// 動的外力 `p` だけを基準にすると、**地動加速度がゼロを横切る時刻**で基準が
/// 消えて床の 1.0（N）まで落ち、判定が「残差 < tol × 1 N」という絶対値判定に
/// 化ける。実建物では内力・慣性力が 1e7 N 規模あり、悪条件な有効剛性の線形解が
/// 持つ残差（概ね `条件数 × ε × 力のスケール`）が 1e-1 N 規模になるため、
/// **原理的に到達できない閾値**になってしまう。正弦波なら毎周期 2 回、実波形でも
/// 頻繁に通る時刻なので、避けようがない。
///
/// 地動が 0 でも構造は動いており慣性力・減衰力は大きい。3 項の最大を採れば、
/// どの項が支配的な時刻でも意味のある基準になる。
pub fn dynamic_reference_norm(p: &[f64], m_a: &[f64], c_v: &[f64]) -> f64 {
    let norm = |v: &[f64]| v.iter().map(|x| x * x).sum::<f64>().sqrt();
    norm(p).max(norm(m_a)).max(norm(c_v)).max(1.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 外力が 0 でも、慣性力・減衰力があれば基準ノルムはそちらを採る。
    ///
    /// 地動加速度がゼロを横切る時刻に相当する。ここで床の 1.0 まで落ちると、
    /// 収束判定が到達不能な絶対値判定に化ける。
    #[test]
    fn 外力がゼロでも慣性力を基準に採る() {
        let p = [0.0, 0.0, 0.0];
        let m_a = [3.0, 4.0, 0.0]; // ノルム 5
        let c_v = [1.0, 0.0, 0.0];
        assert_eq!(dynamic_reference_norm(&p, &m_a, &c_v), 5.0);
    }

    /// 3 項のうち最大のものを採る。
    #[test]
    fn 動的釣り合いの各項の最大を採る() {
        assert_eq!(dynamic_reference_norm(&[7.0], &[3.0], &[5.0]), 7.0);
        assert_eq!(dynamic_reference_norm(&[3.0], &[7.0], &[5.0]), 7.0);
        assert_eq!(dynamic_reference_norm(&[3.0], &[5.0], &[7.0]), 7.0);
    }

    /// 完全に静止している（3 項とも 0）ときは床の 1.0 を返す（0 除算の回避）。
    #[test]
    fn 静止時は床の一を返す() {
        assert_eq!(dynamic_reference_norm(&[0.0], &[0.0], &[0.0]), 1.0);
        assert_eq!(dynamic_reference_norm(&[0.5], &[0.2], &[0.1]), 1.0);
    }
}
